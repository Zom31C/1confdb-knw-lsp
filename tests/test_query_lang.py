def test_check_group_by(ctx):
    # каноническое ключевое слово 1С — СГРУППИРОВАТЬ ПО
    errs = check_query(
        'ВЫБРАТЬ Т.СсылкаАтрибут.Наименование КАК N, '
        'СУММА(Т.СсылкаАтрибут.Наименование) КАК S '
        'ИЗ Справочник.Справочник1 КАК Т '
        'СГРУППИРОВАТЬ ПО Т.СсылкаАтрибут.Наименование', ctx)
    assert errs == []
