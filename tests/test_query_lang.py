def test_parse_grouping_sets_flat():
    # плоская форма ГРУППИРУЮЩИМ НАБОРАМ (GROUPING) — без вложенных скобок
    st = parse_query('ВЫБРАТЬ Т.Склад, СУММА(Т.Кол) ИЗ Документ.Д КАК Т '
                     'СГРУППИРОВАТЬ ПО ГРУППИРУЮЩИМ НАБОРАМ (Т.Склад, Т.Товар)')
    assert len(st[0]['group']) == 2
    # вложенная форма по-прежнему разбирается
    st = parse_query('ВЫБРАТЬ Т.Склад, СУММА(Т.Кол) ИЗ Документ.Д КАК Т '
                     'СГРУППИРОВАТЬ ПО ГРУППИРУЮЩИМ НАБОРАМ '
                     '((Т.Склад), (Т.Склад, Т.Товар))')
    assert len(st[0]['group']) == 3


