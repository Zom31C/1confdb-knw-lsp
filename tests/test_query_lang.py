def test_reject_non_language():
    # ЕСТЬ ИЕРАРХИЯ не входит в язык запросов (только ЕСТЬ [НЕ] NULL)
    with pytest.raises(Exception):
        parse_query('ВЫБРАТЬ Т.Х ИЗ Документ.Д КАК Т ГДЕ Т.Х ЕСТЬ ИЕРАРХИЯ')
    # операция % (остаток) в языке запросов отсутствует
    with pytest.raises(Exception):
        parse_query('ВЫБРАТЬ Т.Х % 2 ИЗ Документ.Д КАК Т')
    # после В обязательны скобки со списком значений или подзапросом
    with pytest.raises(Exception):
        parse_query('ВЫБРАТЬ Т.Х ИЗ Документ.Д КАК Т ГДЕ Т.Х В &П')


