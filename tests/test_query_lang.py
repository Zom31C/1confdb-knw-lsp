def test_check_enum_predefined_common(ctx):
    # значения перечисления — допустимые «поля» объекта перечисления
    assert check_query('ВЫБРАТЬ Т.Значение1 ИЗ Перечисление.ТестПеречисление КАК Т',
                       ctx) == []
    # предопределённые элементы и общий реквизит (прикреплён к справочнику)
    assert check_query('ВЫБРАТЬ Т.ПредЗначение ИЗ Справочник.Справочник1 КАК Т',
                       ctx) == []
    assert check_query('ВЫБРАТЬ Т.ОбщийТест ИЗ Справочник.Справочник1 КАК Т', ctx) == []
    # значения перечисления не являются полем справочника
    errs = check_query('ВЫБРАТЬ Т.Значение1 ИЗ Справочник.Справочник1 КАК Т', ctx)
    assert any('неизвестное поле' in e for e in errs)


